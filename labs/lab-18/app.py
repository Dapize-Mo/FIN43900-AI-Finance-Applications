# Helper to collect all verified numbers printed by the script
def extract_printed_numbers(data_dict: dict) -> set:
    """Extracts all numbers printed by the code into a normalized set for validation."""
    printed = set()
    # Add numbers from rows
    for r in data_dict["rows"]:
        for k in ["revenue", "net_income", "operating_cash_flow", "capital_spending", "equity", "roe", "owner_earnings", "current_ratio", "liabilities_equity"]:
            val = r.get(k)
            if isinstance(val, (int, float)):
                printed.add(str(val))
                if isinstance(val, float):
                    printed.add(f"{val:.1f}")
                    printed.add(f"{val:.2f}")
                if isinstance(val, int):
                    printed.add(f"{val:,}")
                    printed.add(str(val))
            # Also add dates parts (e.g. 2022, 2023, 2024, 2025, 2026, 08, 28, etc.)
            d_parts = r["fy_end"].split("-")
            for p in d_parts:
                printed.add(p)
                printed.add(str(int(p)))
    # Add check constants and common structural integers
    printed.update(["15", "15.0", "1", "2", "3", "5", "10", "50", "70", "0", "0.0"])
    # CIK
    printed.add(str(int(data_dict["cik"])))
    return printed


def audit_memo_numbers(memo_text: str, allowed_numbers: set):
    """
    Finds every number in the memo and flags numbers that were not printed by the script.
    Returns (flagged_numbers, highlighted_memo_html).
    """
    # Regex to extract numbers (including percentages and currency)
    # Matches numbers like 28.3, 226,954, 40.0%, $5,844
    number_pattern = re.compile(r'(?:\$)?\b\d+(?:,\d{3})*(?:\.\d+)?%?')
    
    flagged = []
    
    def replace_match(match):
        raw_token = match.group(0)
        # Strip currency symbols, commas, percent
        cleaned = raw_token.replace('$', '').replace('%', '').replace(',', '').strip()
        
        # Check against allowed numbers
        is_allowed = (
            cleaned in allowed_numbers or 
            raw_token in allowed_numbers or
            raw_token.replace('$', '') in allowed_numbers or
            raw_token.replace('%', '') in allowed_numbers or
            (cleaned.endswith('.0') and cleaned[:-2] in allowed_numbers)
        )
        
        if not is_allowed:
            flagged.append(raw_token)
            return f'<span style="background-color: #ff4b4b; color: white; padding: 2px 6px; border-radius: 4px; font-weight: bold;">⚠️ {raw_token} [UNPRINTED / FLAGGED]</span>'
        return raw_token

    annotated_html = number_pattern.sub(replace_match, memo_text)
    return flagged, annotated_html


